#!/usr/bin/env python3
"""Write eval/judge-audit.md: random judge calls for a hand check.

    python3 research/eval/judge_audit.py                          # experiment 11 judge.json, 30 calls
    python3 research/eval/judge_audit.py --judge sonnet --n 50    # API judge v2 calls, every arm
    python3 research/eval/judge_audit.py --judge sonnet --n 50 --final v2.opus --final-n 15

A judge call is one eligible referee concern against one review. Each item shows the
referee's words, the extractor's summary, the review excerpt the judge quoted (empty for
"not raised") and the verdict. The method behind each review is left out so the check stays
blind; the key at the bottom maps item numbers to methods. No physics needed: the question
is whether the excerpt says what the concern says.
"""
import argparse
import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REF = ROOT / "referee"


def calls():
    out = []
    for p in json.loads((REF / "papers.json").read_text())["papers"]:
        jf = REF / p["id"] / "judge.json"
        if not jf.exists():
            continue
        j = json.loads(jf.read_text())
        con = {c["id"]: c for c in json.loads((REF / p["id"] / "referee.json").read_text())["concerns"]}
        for m in j["matches"]:
            if m.get("fixed_in_v1"):
                continue
            for s in "AB":
                f = p["judge_" + s]
                out.append({"paper": p["id"], "concern": m["concern"], "c": con[m["concern"]],
                            "verdict": m[s], "excerpt": m.get(s + "_quote") or "",
                            "file": f"referee/{p['id']}/{f}",
                            "method": "assistant" if f.startswith("assistant") else "plain"})
    return out


LEGACY = {"legacy.assistant": "assistant-r1/report.md", "legacy.plain": "plain/review.txt"}
EXCLUDED = ("presentation or clarity", "novelty, significance or prior work")


def api_calls(judge):
    """Judge v2 calls under referee/<id>/api/<arm>/, eligible concerns only (as score.py)."""
    out = []
    for pdir in sorted(REF.iterdir()):
        api = pdir / "api"
        if not api.is_dir() or not (pdir / "referee.json").exists():
            continue
        ref = json.loads((pdir / "referee.json").read_text())
        old = pdir / "judge.json"
        fixed = {m["concern"] for m in json.loads(old.read_text())["matches"] if m.get("fixed_in_v1")} if old.exists() else set()
        con = {c["id"]: c for c in ref["concerns"] if c["category"] not in EXCLUDED and c["id"] not in fixed
               and (old.exists() or c.get("in_v1") is not False)}
        for jf in sorted(api.glob(f"*/r*.judge.{judge}.json")):
            arm, k = jf.parent.name, jf.name.split(".")[0][1:]
            f = f"referee/{pdir.name}/" + (LEGACY[arm] if arm in LEGACY else f"api/{arm}/r{k}.txt")
            got = {m["concern"]: m for m in json.loads(jf.read_text())["matches"]}
            for cid, c in con.items():
                m = got.get(cid, {"verdict": "not raised"})
                out.append({"paper": pdir.name, "concern": cid, "c": c, "verdict": m["verdict"],
                            "excerpt": m.get("quote") or "", "file": f, "method": arm})
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=30)
    ap.add_argument("--seed", type=int, default=11)
    ap.add_argument("--judge", help="an API judge (config.json name); default: experiment 11 judge.json")
    ap.add_argument("--final", help="arm of the final candidate; at least --final-n calls come from it")
    ap.add_argument("--final-n", type=int, default=15)
    a = ap.parse_args()
    pool = api_calls(a.judge) if a.judge else calls()
    rnd = random.Random(a.seed)
    if a.final:
        fin = [c for c in pool if c["method"] == a.final]
        pick = rnd.sample(fin, min(a.final_n, len(fin)))
        rest = [c for c in pool if c not in pick]
        pick += rnd.sample(rest, a.n - len(pick))
        rnd.shuffle(pick)
    else:
        pick = rnd.sample(pool, a.n)
    source = (f"the {a.judge} judge (judge v2, Claude-judged, provisional)" if a.judge
              else "the referee match, experiment 11 in `../eval.md`")
    L = [f"# Judge audit: {a.n} judge calls to check by hand", "",
         f"*Generated by `judge_audit.py` (seed {a.seed}{', --judge ' + a.judge if a.judge else ''}) from {source}. "
         "Do not edit by hand; fill the Your verdict lines.*", "",
         "Each item is one referee concern and one review. The judge said whether the review "
         "raised the concern (**raised**), touched it (**partly**) or missed it (**not raised**). "
         "Read the concern and the excerpt and write your own verdict. For **not raised** there is "
         "no excerpt: open the review file and search it for the concern's topic.", "",
         f"Pool: {len(pool)} judge calls on {len({c['paper'] for c in pool})} papers. "
         f"In this sample: " + ", ".join(f"{sum(c['verdict'] == v for c in pick)} {v}"
                                         for v in ("raised", "partly", "not raised")) + ".", ""]
    for i, c in enumerate(pick, 1):
        con = c["c"]
        L += [f"## {i}. Paper {c['paper']}, concern {c['concern']} ({con['category']}, {con['severity']})", "",
              f"> {con['quote']}", "",
              f"Extractor's summary: \"{con['summary']}\"", "",
              "Review excerpt:" if c["excerpt"] else "Review excerpt: (none)", "",
              *([f"> {c['excerpt']}", ""] if c["excerpt"] else []),
              f"Review file: `{c['file']}`", "",
              f"Judge: **{c['verdict']}**", "",
              "Your verdict (raised / partly / not raised):", "",
              "Note:", ""]
    L += ["## Key (read after checking)", "", "| Item | Method |", "|---|---|"]
    L += [f"| {i} | {c['method']} |" for i, c in enumerate(pick, 1)]
    (ROOT / "judge-audit.md").write_text("\n".join(L) + "\n")
    print(f"wrote judge-audit.md: {a.n} of {len(pool)} calls")


if __name__ == "__main__":
    main()
